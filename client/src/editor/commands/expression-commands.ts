/**
 * Define every slash-menu command. Contains the hand-written expression templates and MathLive’s symbols, functions, and macros. A symbol uses the same command shape as a template, including variants. An empty search lists only the templates.
 *
 * @file
 */

import { commandUsageRelevance } from './command-relevance.ts'

/** Describe one insertable command. `relevance` is how often it is typed, and a larger number sorts first among equally close matches. A variant is the same kind of command and may itself have variants. */
export interface ExpressionCommand {
  id: string
  label: string
  symbol: string
  keywords: readonly string[]
  latex: string
  relevance: number
  variants?: readonly ExpressionCommand[]
}

/** A command before its usage score is attached. Variants use the same shape. */
interface ExpressionCommandDraft {
  id: string
  label: string
  symbol: string
  keywords: readonly string[]
  latex: string
  variants?: readonly ExpressionCommandDraft[]
}

/** Copy a command and record how often its name is typed. Each variant keeps its own score. */
function withRelevance(command: ExpressionCommandDraft): ExpressionCommand {
  const { variants, ...commandWithoutVariants } = command
  const relevance = commandUsageRelevance(command.id, command.keywords)
  if (!variants?.length) return { ...commandWithoutVariants, relevance }
  return { ...commandWithoutVariants, relevance, variants: variants.map(withRelevance) }
}

