/** Give a command with no survey entry a low score so it stays below everyday notation. */
const unlistedCommandRelevance = 100

/** Return the usage score for a command. Names that draw one symbol share the highest score among those names, and a notebook floor can raise a command the survey underrated. */
export function commandUsageRelevance(id: string, keywords: readonly string[] = []) {
  let best = notebookRelevance[id] ?? unlistedCommandRelevance
  for (const name of [id, ...keywords]) {
    const score = latexSearchRelevance[name]
    if (score !== undefined && score > best) best = score
  }
  return best
}
